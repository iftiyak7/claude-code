/**
 * Flat key => default map.
 */
function nmo_defaults() {
	$out = array();
	foreach ( nmo_fields() as $section ) {
		foreach ( $section['fields'] as $key => $f ) {
			$out[ $key ] = $f[2];
		}
	}
	return $out;
}
