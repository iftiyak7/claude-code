/**
 * Flat key => default map.
 */
function nsl_defaults() {
	$out = array();
	foreach ( nsl_fields() as $section ) {
		foreach ( $section['fields'] as $key => $f ) {
			$out[ $key ] = $f[2];
		}
	}
	return $out;
}
