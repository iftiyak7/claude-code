#!/usr/bin/env python3
"""
Bundle Tafsir Ibn Kathir in Bangla (Tawheed Publication translation, as
published on Quran.com / QUL) for offline reading.

The source has one entry per ayah, but a passage often covers several ayat
and is repeated for each; we store every passage once with its ayah range.

Output
  assets/tafsir/ik-<surah>.ttxt   lines "from-to \x1f text" (paragraph breaks as \x1e)
  src/quran/tafsirFiles.ts        static require() map

Usage: python3 -I scripts/build-tafsir.py <dir with 1.json … 114.json>
"""
import json
import os
import re
import sys

SRC = sys.argv[1]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'assets', 'tafsir')
META = json.load(open(os.path.join(ROOT, 'src', 'quran', 'meta.json'), encoding='utf-8'))


def clean(t):
    t = t.replace('\r', '').replace('\x1f', ' ')
    t = re.sub(r'<[^>]+>', '', t)
    paras = [re.sub(r'[ \t]+', ' ', p).strip() for p in t.split('\n')]
    return '\x1e'.join(p for p in paras if p)


def main():
    os.makedirs(OUT, exist_ok=True)
    total_ayat = 0
    lines_ts = ['// Generated by scripts/build-tafsir.py — do not edit.', '/* eslint-disable @typescript-eslint/no-require-imports */', 'export const TAFSIR_FILES: Record<number, number> = {']
    for s in range(1, 115):
        rows = json.load(open(os.path.join(SRC, f'{s}.json'), encoding='utf-8'))
        rows.sort(key=lambda r: r['ayah'])
        expected = META['surahs'][s - 1]['ayahs']
        ayat = [r['ayah'] for r in rows]
        if ayat != list(range(1, expected + 1)):
            raise SystemExit(f'surah {s}: ayah list does not match the mushaf ({len(ayat)} vs {expected})')
        groups = []
        for r in rows:
            text = clean(r['text'])
            if groups and groups[-1][2] == text:
                groups[-1][1] = r['ayah']
            else:
                groups.append([r['ayah'], r['ayah'], text])
        with open(os.path.join(OUT, f'ik-{s}.ttxt'), 'w', encoding='utf-8') as f:
            f.write('\n'.join(f'{a}-{b}\x1f{t}' for a, b, t in groups))
        lines_ts.append(f"  {s}: require('../../assets/tafsir/ik-{s}.ttxt'),")
        total_ayat += expected
    lines_ts += ['};', '']
    open(os.path.join(ROOT, 'src', 'quran', 'tafsirFiles.ts'), 'w', encoding='utf-8').write('\n'.join(lines_ts))
    size = sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT))
    print(f'tafsir for {total_ayat} ayat in 114 files, {size / 1e6:.1f} MB')


main()
