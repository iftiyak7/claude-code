export const dictionaries = { bn, en };

export function getT(lang: 'bn' | 'en'): Dict {
  return dictionaries[lang];
}

export function useT(): Dict {
  const lang = useData((s) => s.settings.language);
  return dictionaries[lang];
}

const BN_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];

/** Localised digits (Bangla numerals in bn). */
export function num(n: number | string, lang: 'bn' | 'en'): string {
  const s = String(n);
  return lang === 'bn' ? s.replace(/\d/g, (d) => BN_DIGITS[Number(d)]) : s;
}

export function useNum() {
  const lang = useData((s) => s.settings.language);
  return (n: number | string) => num(n, lang);
}
